"""Sorted source IDs preserve the full bounded relation, including sparse IDs."""
import pytest
import somtparser as sp

from test_btor2_streamed_input import (
    PINS, bounded_relation, equivalent, source, translated_after_source_release,
)


def reindex_source(text, layout):
    rows = [line.split(';', 1)[0].split() for line in text.splitlines()]
    rows = [row for row in rows if row]
    maximum = max(int(row[0]) for row in rows)
    boolean_sort = next(int(row[0]) for row in rows if row[1:] == ['sort', 'bitvec', '1'])
    # Keep every original relation and add a reachable witness. These are
    # explicitly derived regressions, not new official benchmark results.
    rows += [[str(maximum + 1), 'one', str(boolean_sort)],
             [str(maximum + 2), 'not', str(boolean_sort), str(maximum + 1)],
             [str(maximum + 3), 'bad', str(-(maximum + 2))]]
    original = '\n'.join(' '.join(row) for row in rows) + '\n'
    size = len(rows)
    ids = ([i + 1 for i in range(size)] if layout == 'dense' else
           [2 * i + 1 for i in range(size)] if layout == 'holes' else
           [(2**63 - 1) - 17 * (size - 1 - i) for i in range(size)])
    mapping = {int(row[0]): value for row, value in zip(rows, ids)}

    def mapped(value):
        value = int(value)
        return str((-1 if value < 0 else 1) * mapping[abs(value)])

    transformed = []
    for row in rows:
        row = row.copy()
        old_id, op = row[0], row[1]
        if op in {'state', 'input'} and len(row) == 3:
            # Explicitly preserve original autogenerated names across renumbering.
            row.append(op + old_id)
        if op == 'sort':
            positions = [3, 4] if row[2] == 'array' else []
        elif op in {'bad', 'constraint', 'output'}:
            positions = [2]
        elif op in {'input', 'state', 'one', 'const', 'constd', 'consth'}:
            positions = [2]
        elif op in {'not', 'uext'}:
            positions = [2, 3]
        elif op in {'write', 'ite'}:
            positions = [2, 3, 4, 5]
        else:
            assert op in {'init', 'next', 'add', 'and', 'or', 'eq', 'ult', 'ugt', 'ugte', 'slt', 'read'}
            positions = [2, 3, 4]
        row[0] = mapping[int(old_id)]
        for position in positions:
            row[position] = mapped(row[position])
        transformed.append(' '.join(map(str, row)))
    return original, '\n'.join(transformed) + '\n'


@pytest.mark.parametrize('name', list(PINS))
@pytest.mark.parametrize('layout', ['dense', 'holes', 'near_llong_max'])
@pytest.mark.parametrize('mode', ['inline', 'path'])
def test_renumbered_official_bv_and_array_transitions(name, layout, mode, tmp_path):
    original, derived = reindex_source(source(name), layout)
    actual = translated_after_source_release(derived, mode, 2, tmp_path)
    # The independent interpretation receives original IDs, not the reindexing
    # map. Both default names and every original transition remain observable.
    equivalent(actual, bounded_relation(original, 2), require_sat=True)


@pytest.mark.parametrize('text,line,diagnostic', [
    ('1 sort bitvec 1\n3 one 1\n4 and 1 3 2\n5 bad 3\n', 3, 'undeclared earlier node 2'),
    ('1 sort bitvec 1\n3 one 1\n4 bad -2\n', 3, 'undeclared earlier node -2'),
    ('1 sort bitvec 1\n3 not 1 5\n5 one 1\n6 bad 3\n', 2, 'undeclared earlier node 5'),
    ('1 sort bitvec 1\n3 one 1\n3 bad 3\n', 3, 'positive and strictly increasing'),
    ('1 sort bitvec 1\n3 one 1\n2 bad 3\n', 3, 'positive and strictly increasing'),
    ('1 sort bitvec 1\n3 one 1\n4 bad -9223372036854775808\n', 3, 'negated node id is out of range'),
])
@pytest.mark.parametrize('mode', ['inline', 'path'])
def test_sparse_lookup_does_not_accept_missing_or_invalid_references(text, line, diagnostic, mode, tmp_path):
    options = dict(language='btor2', profile='bmc', options={'bmc_depth': '1'})
    if mode == 'inline':
        result = sp.translate(source=text, **options)
    else:
        path = tmp_path / 'invalid-sparse.btor2'
        path.write_text(text)
        result = sp.translate(path=str(path), **options)
    assert not result.ok
    assert any(d.line == line and diagnostic in d.message for d in result.diagnostic_items)


def test_only_live_names_and_literals_outlive_the_inline_source():
    state_name = 'state signal with an unusually long preserved label'
    input_name = 'input signal with spaces and a long preserved label'
    ignored_gate_name = 'annotation that belongs to a gate and must not be emitted'
    text = (f'1 sort bitvec 1\n'
            f'2 state 1 {state_name}\n'
            f'3 input 1 {input_name}\n'
            f'4 one 1 {ignored_gate_name}\n'
            f'5 not 1 4 {ignored_gate_name}\n'
            f'6 next 1 2 5\n'
            f'7 output 3 observed input signal\n'
            f'8 bad 4\n')
    expected = bounded_relation(text, 1)
    result = sp.translate(source=text, language='btor2', profile='bmc',
                          options={'bmc_depth': '1'})
    del text
    assert result.ok, [d.message for d in result.diagnostic_items]
    script = result.to_smt2()
    assert state_name in script
    assert input_name in script
    assert 'observed input signal' in script
    assert ignored_gate_name not in script
    import z3
    equivalent(z3.And(*z3.parse_smt2_string(script)), expected, require_sat=True)


def test_duplicate_state_and_output_names_keep_the_existing_disambiguation():
    shared_name = 'shared state output label with spaces'
    text = (f'1 sort bitvec 1\n'
            f'2 state 1 {shared_name}\n'
            f'3 output 2 {shared_name}\n'
            f'4 one 1\n'
            f'5 bad 4\n')
    result = sp.translate(source=text, language='btor2', profile='bmc',
                          options={'bmc_depth': '0'})
    del text
    assert result.ok, [d.message for d in result.diagnostic_items]
    script = result.to_smt2()
    assert shared_name + '@0' in script
    assert shared_name + '$3@0' in script


def test_long_constant_literal_survives_inline_source_release(tmp_path):
    bits = '0' * 63 + '1'
    text = (f'1 sort bitvec 64\n'
            f'2 sort bitvec 1\n'
            f'3 const 1 {bits}\n'
            f'4 state 1 state_for_literal_test\n'
            f'5 eq 2 3 4\n'
            f'6 bad 5\n')
    expected = bounded_relation(text, 0)
    actual = translated_after_source_release(text, 'inline', 0, tmp_path)
    equivalent(actual, expected, require_sat=True)


@pytest.mark.parametrize(('justice_line', 'diagnostic'), [
    ('3 justice 5 2 2 2 2 2', "'justice' is a liveness property"),
    ('3 justice 5 2 2 2 2 -99', 'undeclared earlier node -99'),
])
def test_multi_operand_justice_keeps_arity_and_checks_every_reference(justice_line, diagnostic):
    text = '1 sort bitvec 1\n2 one 1\n' + justice_line + ' justice label with spaces\n'
    result = sp.translate(source=text, language='btor2', profile='bmc',
                          options={'bmc_depth': '1'})
    assert not result.ok
    assert any(diagnostic in d.message for d in result.diagnostic_items)


def test_unknown_operator_keeps_its_original_diagnostic():
    result = sp.translate(source='1 sort bitvec 1\n2 mystery_tag 1 1\n',
                          language='btor2', profile='bmc',
                          options={'bmc_depth': '1'})
    assert not result.ok
    assert any('unknown BTOR2 tag `mystery_tag`' in d.message
               for d in result.diagnostic_items)
